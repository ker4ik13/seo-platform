import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../../", import.meta.url));
const directory = path.join(root, "docs/i18n");
const catalog = JSON.parse(await readFile(path.join(directory, "ui-catalog.json"), "utf8"));
const translations = {};
for (const file of (await readdir(directory)).filter(name => /^en-\d{4}\.json$/u.test(name)).sort()) {
  const chunk = JSON.parse(await readFile(path.join(directory, file), "utf8"));
  for (const [index, value] of Object.entries(chunk)) {
    if (index in translations) throw new Error(`Duplicate translation index ${index}`);
    translations[index] = value;
  }
}
const placeholders = value => [...value.matchAll(/\{\d+\}/gu)].map(match => match[0]).sort().join(",");
const dictionary = {};
for (const [index, entry] of catalog.entries()) {
  const english = translations[index];
  if (typeof english !== "string" || !english) throw new Error(`Missing translation ${index}: ${entry.text}`);
  if (placeholders(entry.text) !== placeholders(english)) throw new Error(`Placeholder mismatch ${index}`);
  dictionary[entry.text] = english;
}
const dynamic = JSON.parse(await readFile(path.join(directory, "dynamic-catalog.json"), "utf8"));
const dynamicTranslations = {};
for (const file of (await readdir(directory)).filter(name => /^en-dynamic-\d{4}\.json$/u.test(name)).sort()) {
  const chunk = JSON.parse(await readFile(path.join(directory, file), "utf8"));
  for (const [index, value] of Object.entries(chunk)) {
    if (index in dynamicTranslations) throw new Error(`Duplicate dynamic index ${index}`);
    dynamicTranslations[index] = value;
  }
}
for (const [index, entry] of dynamic.entries()) {
  const english = dynamicTranslations[index];
  if (english === null) continue; // Explicitly reviewed code examples / data constants.
  if (typeof english !== "string" || !english) throw new Error(`Missing dynamic translation ${index}: ${entry.text}`);
  if (placeholders(entry.text) !== placeholders(english)) throw new Error(`Dynamic placeholder mismatch ${index}`);
  dictionary[entry.text] = english;
}
const extraFile = path.join(directory, "en-extra.json");
try { Object.assign(dictionary, JSON.parse(await readFile(extraFile, "utf8"))); } catch (error) { if (error.code !== "ENOENT") throw error; }
for (const [key, value] of Object.entries(dictionary)) {
  if (placeholders(key) !== placeholders(value)) throw new Error(`Placeholder mismatch: ${key}`);
}
const output = `/** Generated by infrastructure/i18n/build-dictionary.mjs. UI copy only; never translate user content. */\nexport const uiEnglish: Readonly<Record<string, string>> = ${JSON.stringify(dictionary, null, 2)};\n`;
const target = path.join(root, "frontend/lib/ui-translations.ts");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("UI dictionary needs regeneration");
} else await writeFile(target, output);
process.stdout.write(`UI dictionary: ${Object.keys(dictionary).length} translations, placeholders checked\n`);
