function presetRules(words: readonly string[]): SemanticNegativeKeywordRules {
  return {
    words,
    matchMode: "WORD_FORM_PRECISE",
    caseSensitive: false,
    ignoreWordOrder: false,
    ignorePunctuation: true
  };
}

function uniqueWords(...collections: readonly (readonly string[])[]): readonly string[] {
  const unique = new Map<string, string>();
  for (const words of collections) {
    for (const word of words) {
      const canonical = word.normalize("NFKC").toLocaleLowerCase("ru-RU");
      if (!unique.has(canonical)) unique.set(canonical, word);
    }
  }
  return [...unique.values()];
}
