-- Normalize historical generic Job titles to a grammar-independent status
-- format. The exact allowlist avoids rewriting user-authored notifications.
UPDATE "notifications"
SET "title" = CASE "title"
  WHEN 'Проверка позиций завершился ошибкой'
    THEN 'Проверка позиций: ошибка'
  WHEN 'Проверка позиций завершён'
    THEN 'Проверка позиций: завершено'
  WHEN 'Проверка позиций завершён частично'
    THEN 'Проверка позиций: завершено частично'
  WHEN 'Проверка позиций отменён'
    THEN 'Проверка позиций: отменено'
  WHEN 'Проверка позиций требует внимания'
    THEN 'Проверка позиций: требуется внимание'
  WHEN 'Сбор частотности завершился ошибкой'
    THEN 'Сбор частотности: ошибка'
  WHEN 'Сбор частотности завершён'
    THEN 'Сбор частотности: завершено'
  WHEN 'Сбор частотности завершён частично'
    THEN 'Сбор частотности: завершено частично'
  WHEN 'Сбор частотности отменён'
    THEN 'Сбор частотности: отменено'
  WHEN 'Сбор частотности требует внимания'
    THEN 'Сбор частотности: требуется внимание'
  ELSE "title"
END
WHERE "resource_type" = 'job'
  AND "title" IN (
    'Проверка позиций завершился ошибкой',
    'Проверка позиций завершён',
    'Проверка позиций завершён частично',
    'Проверка позиций отменён',
    'Проверка позиций требует внимания',
    'Сбор частотности завершился ошибкой',
    'Сбор частотности завершён',
    'Сбор частотности завершён частично',
    'Сбор частотности отменён',
    'Сбор частотности требует внимания'
  );
